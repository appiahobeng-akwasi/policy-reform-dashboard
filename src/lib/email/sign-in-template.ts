// The sign-in email is sent by the identity provider (Supabase Auth), which uses one template
// for everyone, so it carries both languages. Its text comes from the i18n catalogues;
// `npm run build:email-templates` writes supabase/templates/sign_in.html from this function.
// {{ .SiteURL }} and {{ .TokenHash }} are filled in by Supabase when the email is sent.
import { LANGUAGES, t, type Lang } from '../../i18n';

export const SIGN_IN_TEMPLATE_PATH = 'supabase/templates/sign_in.html';

const LINK = '{{ .SiteURL }}/auth/confirm?token_hash={{ .TokenHash }}&type=email';

function escapeHtml(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function section(lang: Lang): string {
  const text = (key: Parameters<typeof t>[1]) => escapeHtml(t(lang, key));
  return [
    `<div lang="${lang}" style="margin:0 0 32px">`,
    `  <h1 style="font-size:20px;margin:0 0 12px">${text('email.heading')}</h1>`,
    `  <p style="margin:0 0 16px">${text('email.body')}</p>`,
    `  <p style="margin:0 0 16px"><a href="${LINK}" style="display:inline-block;padding:10px 18px;background:#0f5c4a;color:#ffffff;text-decoration:none;border-radius:4px">${text('email.button')}</a></p>`,
    `  <p style="margin:0;color:#555555;font-size:14px">${text('email.ignore')}</p>`,
    `</div>`,
  ].join('\n');
}

export function signInEmailSubject(): string {
  return LANGUAGES.map((lang) => t(lang, 'email.subject')).join(' | ');
}

export function signInEmailHtml(): string {
  return [
    '<!-- Generated by npm run build:email-templates from src/i18n. Do not edit by hand. -->',
    '<!doctype html>',
    '<html>',
    '<body style="font-family:Arial,Helvetica,sans-serif;font-size:16px;line-height:1.5;color:#1a1a1a;max-width:560px;margin:0 auto;padding:24px">',
    LANGUAGES.map(section).join('\n<hr style="border:none;border-top:1px solid #dddddd;margin:0 0 32px">\n'),
    '</body>',
    '</html>',
    '',
  ].join('\n');
}
